@skipUnless(
    all([CDB_PATH, DLL_PATH, VERSION]),
    "SOFiSTiK environment variables not set!"
)
class SOFiSTiKCDBReaderBeamStressTestSuite(TestCase):
    def setUp(self) -> None:
        self.load_cases = [1000, 2000]

        self.cdb = SOFiSTiKCDBReader(
            CDB_PATH,  # type: ignore
            "BEAM_STRESS",
            DLL_PATH,  # type: ignore
            VERSION  # type: ignore
        )
        self.cdb.open()
        self.cdb.beams.stresses.load(self.load_cases)

    def tearDown(self) -> None:
        self.cdb.close()

    def test_data(self) -> None:
        data = DataFrame(
            _DATA,
            columns=_COLUMNS
        ).set_index(["ELEM_ID", "LOAD_CASE", "POS_REL", "POINT"], drop=False)
        data.sort_index(inplace=True)

        # NOTE:
        # Float values loaded from the CDB contain inherent numerical noise.
        # The chosen tolerance is stricter than pandas default and reflects the
        # maximum relative error observed in practice, ensuring stable and
        # reproducible comparisons.
        assert_frame_equal(data, self.cdb.beams.stresses.get_data(), rtol=1E-7)

    def test_get(self) -> None:
        with self.subTest(msg="SIGC"):
            self.assertEqual(
                self.cdb.beams.stresses.get(202, 1000, 0.50, "02", "SIGC"),
                28919.802734375
            )

        with self.subTest(msg="SIGT"):
            self.assertEqual(
                self.cdb.beams.stresses.get(101, 1000, 1, "Z-", "SIGC"),
                -140069.5625
            )

        with self.subTest(msg="TAU"):
            self.assertEqual(
                self.cdb.beams.stresses.get(101, 1000, 0, "Y+", "TAU"),
                34956.21875
            )

        with self.subTest(msg="SIGV"):
            self.assertEqual(
                self.cdb.beams.stresses.get(202, 2000, 0.5, "03", "SIGV"),
                222438.84375
            )

        with self.subTest(msg="SI"):
            self.assertEqual(
                self.cdb.beams.stresses.get(202, 2000, 1, "11", "SI"),
                2949.359130859375
            )

        with self.subTest(msg="SII"):
            self.assertEqual(
                self.cdb.beams.stresses.get(101, 2000, 0, "Z+", "SII"),
                -45574.3125
            )

        with self.subTest(msg="Not existing with default"):
            self.assertEqual(
                self.cdb.beams.stresses.get(101, 1001, 0, "TAU", "MT2", 1),
                1
            )

    def test_get_after_clear(self) -> None:
        self.cdb.beams.stresses.clear(1000)
        with self.subTest(msg="Check clear method"):
            with self.assertRaises(LookupError):
                self.cdb.beams.stresses.get(101, 1000, 0, "Y+", "TAU")

        self.cdb.beams.stresses.load(1000)
        with self.subTest(msg="Check indexes management"):
            self.assertEqual(
                self.cdb.beams.stresses.get(101, 2000, 0, "Z+", "SII"),
                -45574.3125
            )

    def test_get_after_clear_all(self) -> None:
        self.cdb.beams.stresses.clear_all()
        with self.subTest(msg="Check clear_all method"):
            with self.assertRaises(LookupError):
                self.cdb.beams.stresses.get(101, 2000, 0, "Z+", "SII")

        self.cdb.beams.stresses.load(self.load_cases)
        with self.subTest(msg="Check indexes management"):
            self.assertEqual(
                self.cdb.beams.stresses.get(101, 1000, 0, "Y+", "TAU"),
                34956.21875
            )

    def test_load_with_duplicated_load_cases(self) -> None:
        self.cdb.beams.stresses.clear_all()
        self.cdb.beams.stresses.load(self.load_cases + [1000])
        self.assertEqual(
                self.cdb.beams.stresses.get(101, 2000, 0, "Z+", "SII"),
                -45574.3125
        )
